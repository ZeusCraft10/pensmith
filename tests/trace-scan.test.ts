// tests/trace-scan.test.ts — the scanner that reads an export before it ships.
//
// An exported document must carry no trace of pensmith and none of the machine
// it was made on. The scanner refuses on the tool's name, a generator stamp, a
// local path or a metadata part, in every format; the author's own words in
// the body are allowed. None of these cases needs Pandoc.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { PDFDocument, PDFName } from 'pdf-lib';
import { scanExportFile, scanText } from '../bin/lib/trace-scan.js';
import { pandocLikeDocx } from './lib/docx-fixture.js';

function tmp(name: string): string {
  return join(mkdtempSync(join(tmpdir(), 'pensmith-scan-')), name);
}

test('scanner: a docx with custom.xml naming local paths is refused', async () => {
  const file = tmp('paper.docx');
  await pandocLikeDocx(file, '/home/someone');
  const found = await scanExportFile(file, 'docx', { sensitivePaths: ['/home/someone'] });
  const whats = new Set(found.map((f) => f.what));
  assert.ok(whats.has('document property part'), JSON.stringify(found));
  assert.ok(found.some((f) => f.part === 'docProps/custom.xml'), 'the custom.xml part is named');
  assert.ok(found.some((f) => f.what === 'document property' && /Application|TotalTime|title/.test(f.match)), JSON.stringify(found));
});

test('scanner: every pattern is caught in text formats, and the author\'s own words are not', () => {
  const ctx = { sensitivePaths: ['/srv/papers/alice-thesis'] };
  const cases: Array<[string, string]> = [
    ['Exported with pensmith.', 'tool name'],
    ['% Generated by a tool', 'generator stamp'],
    ['pdfcreator={LaTeX via pandoc}', 'generator stamp'],
    ['see /home/alice/notes.txt', 'absolute local path'],
    ['C:\\Users\\alice\\paper\\x.bib', 'absolute local path'],
    ['url = {file:///home/alice/x.pdf}', 'absolute local path'],
    ['read .paper/CITATIONS.bib', 'paper folder path'],
    ['~/.claude/plugins/cache', 'Claude folder path'],
    ['the folder /srv/papers/alice-thesis/out', 'local path of this machine'],
  ];
  for (const [text, what] of cases) {
    const found = scanText(text, ctx);
    assert.ok(found.some((f) => f.what === what), `${JSON.stringify(text)} must be caught as ${what}: ${JSON.stringify(found)}`);
  }
  // URLs are not local paths.
  assert.deepEqual(scanText('https://example.org/home/x and https://doi.org/10.1/Users/y', {}), []);
  // A paper that discusses the tool or quotes a path keeps its words.
  const author = 'We evaluate pensmith; output generated by models is common in /home/ dirs like /home/demo.';
  assert.deepEqual(scanText(author, { authorText: author }), []);
  // A cited title may say "generated by"; it never excuses a path.
  assert.deepEqual(scanText('Text generated by GPT-2', { bibliographicText: 'Detecting text generated by GPT-2' }), []);
  assert.equal(scanText('/home/alice/x.pdf', { bibliographicText: '/home/alice/x.pdf' }).length, 1);
});

test('scanner: a PDF with an info dictionary or XMP is refused; one without passes', async () => {
  const dirty = await PDFDocument.create();
  dirty.addPage();
  dirty.setProducer('pdfTeX-1.40.25');
  dirty.catalog.set(PDFName.of('Metadata'), dirty.context.register(dirty.context.flateStream('<x:xmpmeta/>', { Type: 'Metadata', Subtype: 'XML' })));
  const a = tmp('dirty.pdf');
  writeFileSync(a, await dirty.save({ useObjectStreams: false }));
  const found = await scanExportFile(a, 'pdf', {});
  assert.ok(found.some((f) => f.what === 'document property'), JSON.stringify(found));
  assert.ok(found.some((f) => f.what === 'XMP metadata'), JSON.stringify(found));

  const clean = await PDFDocument.create({ updateMetadata: false });
  clean.addPage();
  clean.context.trailerInfo.Info = clean.context.register(clean.context.obj({}));
  const b = tmp('clean.pdf');
  writeFileSync(b, await clean.save({ useObjectStreams: false }));
  assert.deepEqual(await scanExportFile(b, 'pdf', {}), []);
});
