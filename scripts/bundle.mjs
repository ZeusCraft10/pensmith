#!/usr/bin/env node
// scripts/bundle.mjs — the committed plugin bundles (PLUG-02, D-23a-04).
//
// A git-marketplace install runs no build step and the plugin cache holds only
// `plugin/`, so the Tier-1 plugin ships self-contained single-file ESM bundles
// with every npm dependency inlined:
//
//   mcp/server.ts           → plugin/dist/mcp/server.mjs      the stdio MCP server
//   bin/lib/pdf-worker.ts   → plugin/dist/mcp/pdf-worker.mjs  the SEC-02 worker, started
//                                                             beside the server bundle
//   hooks/<name>.ts         → plugin/dist/hooks/<name>.mjs    the 4 hook entries
//
// Options (D-23a-04): ESM, platform node, target node22, bundled, no code
// splitting (one file per entry), not minified (readable, reviewable diffs),
// keepNames, legal comments kept inline (REL-10). `.mjs` because `plugin/`
// has no package.json to say "type": "module".
//
// - A createRequire banner gives the bundled CommonJS dependencies a real
//   `require` for Node builtins (esbuild's ESM output otherwise throws
//   `Dynamic require of "fs" is not supported`).
// - pdf-parse picks its PDF.js build with a template-literal require
//   (require(`./pdf.js/${options.version}/build/pdf.js`)), which esbuild
//   cannot follow. The static-require plugin below rewrites that one call to
//   the pinned v1.10.100 build (the only version pensmith asks for) in the
//   bundle's copy — never by patching node_modules.
// - Optional dependencies that a bundled package tries inside try/catch and
//   pensmith never installs resolve to a module that fails like an absent
//   package, so a bundle never loads code from a node_modules outside itself.
// - No __dirname / __filename shim: no code path pensmith runs reads them in a
//   bundle. The one dependency function that does (sync-fetch's worker spawn,
//   under citation-js) is never called: pensmith hands citation-js only CSL
//   and BibTeX with a forced input type, and http.ts is the one egress gate.
//
// Output is byte-deterministic: LF line endings, esbuild's module comments name
// paths relative to the repo root (absWorkingDir), and the build fails if an
// absolute path of this checkout appears in a bundle.
//
// `npm run bundle` regenerates plugin/dist (prebuild first: the sources import
// bin/lib/version.generated.ts). `npm run bundle:check` (= bundle --check)
// then fails when plugin/dist differs from what git has committed — a
// modified, deleted or new file (CI and `npm run check`). Rebundle after any
// change to bin/lib, mcp/ or hooks/, and commit plugin/dist with it.

import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = path.join(repoRoot, 'plugin', 'dist');

/** Entry source (repo-relative, POSIX) → output (relative to plugin/dist, POSIX). */
export const BUNDLE_ENTRIES = Object.freeze({
  'mcp/server.ts': 'mcp/server.mjs',
  'bin/lib/pdf-worker.ts': 'mcp/pdf-worker.mjs',
  'hooks/session-start.ts': 'hooks/session-start.mjs',
  'hooks/pre-compact.ts': 'hooks/pre-compact.mjs',
  'hooks/post-tool-use.ts': 'hooks/post-tool-use.mjs',
  'hooks/stop.ts': 'hooks/stop.mjs',
});

const BANNER = [
  '// Generated by scripts/bundle.mjs from the pensmith sources. Do not edit:',
  '// run `npm run bundle` (CI fails when this file drifts from its sources).',
  "import { createRequire as __pensmithCreateRequire } from 'node:module';",
  'const require = __pensmithCreateRequire(import.meta.url);',
].join('\n');

/** The one PDF.js build pdf-parse is asked for (bin/lib/pdf-worker.ts passes no version). */
const PDFJS_VERSION = 'v1.10.100';

/**
 * Rewrite pdf-parse's versioned template-literal require to a static require
 * of the pinned build, so esbuild inlines it. Any other version throws, as a
 * missing build would have.
 */
const pdfParseStaticRequire = {
  name: 'pensmith-pdf-parse-static-require',
  setup(b) {
    b.onLoad({ filter: /[\\/]pdf-parse[\\/]lib[\\/]pdf-parse\.js$/ }, (args) => {
      const src = readFileSync(args.path, 'utf8');
      const dynamic = 'require(`./pdf.js/${options.version}/build/pdf.js`)';
      if (!src.includes(dynamic)) {
        throw new Error(`bundle: pdf-parse's versioned require changed shape in ${args.path}; update scripts/bundle.mjs`);
      }
      const pinned =
        `(options.version === '${PDFJS_VERSION}' ? require('./pdf.js/${PDFJS_VERSION}/build/pdf.js') ` +
        `: (() => { throw new Error('pdf-parse: only the bundled PDF.js ${PDFJS_VERSION} is available, not ' + options.version); })())`;
      return { contents: src.replace(dynamic, pinned), loader: 'js' };
    });
  },
};

/**
 * Optional dependencies a bundled package requires inside try/catch and that
 * pensmith never installs: node-fetch's `encoding` (reached through
 * citation-js). Left external, the bundle would look for them at runtime in
 * whatever node_modules sits above the plugin cache.
 */
const ABSENT_OPTIONAL_DEPENDENCIES = ['encoding'];

const absentOptionalDependencies = {
  name: 'pensmith-absent-optional-dependencies',
  setup(b) {
    const filter = new RegExp(`^(${ABSENT_OPTIONAL_DEPENDENCIES.join('|')})$`);
    b.onResolve({ filter }, (args) => ({ path: args.path, namespace: 'pensmith-absent' }));
    b.onLoad({ filter: /.*/, namespace: 'pensmith-absent' }, (args) => ({
      contents:
        `const e = new Error(${JSON.stringify(`Cannot find module '${args.path}' (not bundled with the pensmith plugin)`)});\n` +
        "e.code = 'MODULE_NOT_FOUND';\nthrow e;\n",
      loader: 'js',
    }));
  },
};

/** Absolute spellings of this checkout that must never reach a bundle. */
function forbiddenPaths() {
  return [...new Set([repoRoot, repoRoot.split(path.sep).join('/')])];
}

/** Bundle one entry and return its final text. */
async function bundleOne(entry) {
  const result = await build({
    absWorkingDir: repoRoot,
    entryPoints: [entry],
    bundle: true,
    write: false,
    outfile: path.join(outRoot, ...BUNDLE_ENTRIES[entry].split('/')),
    format: 'esm',
    platform: 'node',
    target: 'node22',
    splitting: false,
    minify: false,
    keepNames: true,
    legalComments: 'inline',
    sourcemap: false,
    charset: 'ascii',
    banner: { js: BANNER },
    logLevel: 'warning',
    plugins: [pdfParseStaticRequire, absentOptionalDependencies],
  });
  if (result.outputFiles.length !== 1) throw new Error(`bundle: ${entry} produced ${result.outputFiles.length} files`);
  // LF only: a dependency source with CRLF must not make a bundle differ by OS.
  const text = result.outputFiles[0].text.replace(/\r\n?/g, '\n');
  for (const p of forbiddenPaths()) {
    if (text.includes(p)) throw new Error(`bundle: ${entry} embeds the absolute path ${p}`);
  }
  return text;
}

/** Fail when plugin/dist differs from what git has committed (modified, deleted or new files). */
function checkCommitted() {
  const status = execFileSync('git', ['status', '--porcelain', '--untracked-files=all', '--', 'plugin/dist'], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
  if (status.trim() === '') {
    process.stdout.write('bundle: plugin/dist matches the committed bundles\n');
    return;
  }
  process.stderr.write(
    'bundle: plugin/dist differs from the committed bundles — run `npm run bundle` and commit plugin/dist:\n' + status,
  );
  try {
    process.stderr.write(execFileSync('git', ['diff', '--stat', '--', 'plugin/dist'], { cwd: repoRoot, encoding: 'utf8' }));
  } catch {
    /* the status above already names the files */
  }
  process.exitCode = 1;
}

async function main() {
  const check = process.argv.includes('--check');
  rmSync(outRoot, { recursive: true, force: true });
  for (const entry of Object.keys(BUNDLE_ENTRIES)) {
    const text = await bundleOne(entry);
    const out = path.join(outRoot, ...BUNDLE_ENTRIES[entry].split('/'));
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, text);
    process.stdout.write(`bundle: ${entry} -> plugin/dist/${BUNDLE_ENTRIES[entry]} (${(Buffer.byteLength(text) / 1024).toFixed(0)} KiB)\n`);
  }
  if (check) checkCommitted();
}

await main();
