// scripts/verb-table.ts — the README command table, generated from the CLI.
//
// Each row comes from the verb's own citty definition (its name, positional
// arguments and meta.description), so the README cannot drift from what
// `pensmith --help` says. tests/docs.test.ts fails when README.md and this
// output differ.
//
//   npm run docs:verbs     rewrite the table in README.md

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { command } from '../bin/pensmith.js';
import { UX02_VERBS } from '../bin/lib/verbs.js';

export const TABLE_START = '<!-- verb-table:start (generated by `npm run docs:verbs`; do not edit) -->';
export const TABLE_END = '<!-- verb-table:end -->';

interface ArgDef { type?: string; required?: boolean }
interface VerbDef { meta?: { description?: string }; args?: Record<string, ArgDef> }

function usage(verb: string, def: VerbDef): string {
  const positionals = Object.entries(def.args ?? {})
    .filter(([, a]) => a.type === 'positional')
    .map(([name, a]) => (a.required === false ? `[${name}]` : `<${name}>`));
  return ['pensmith', verb, ...positionals].join(' ');
}

// Description text goes into a markdown table cell: escape pipes, and angle
// brackets so `<n>` is shown rather than swallowed as an HTML tag.
const cell = (s: string): string =>
  s.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\s+/g, ' ').trim();

/** The markdown table, one row per verb in dispatcher order. */
export async function renderVerbTable(): Promise<string> {
  const subs = command.subCommands as Record<string, () => Promise<VerbDef>>;
  const rows = ['| Command | What it does |', '| --- | --- |'];
  for (const verb of UX02_VERBS) {
    const load = subs[verb];
    if (!load) throw new Error(`verb ${verb} is not registered in bin/pensmith.ts`);
    const def = await load();
    rows.push(`| \`${usage(verb, def)}\` | ${cell(def.meta?.description ?? '')} |`);
  }
  return rows.join('\n');
}

/** The README section between the markers, or null when the markers are missing. */
export function extractTable(readme: string): string | null {
  const start = readme.indexOf(TABLE_START);
  const end = readme.indexOf(TABLE_END);
  if (start === -1 || end === -1 || end < start) return null;
  return readme.slice(start + TABLE_START.length, end).trim();
}

const readmeUrl = new URL('../README.md', import.meta.url);

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const readme = readFileSync(readmeUrl, 'utf8');
  if (extractTable(readme) === null) {
    console.error(`README.md has no ${TABLE_START} … ${TABLE_END} block`);
    process.exit(1);
  }
  const start = readme.indexOf(TABLE_START) + TABLE_START.length;
  const end = readme.indexOf(TABLE_END);
  const next = `${readme.slice(0, start)}\n${await renderVerbTable()}\n${readme.slice(end)}`;
  writeFileSync(readmeUrl, next);
  console.log('README.md command table regenerated');
}
